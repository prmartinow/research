import { PGlite } from '@electric-sql/pglite';

export const db = new PGlite();

export async function initDatabase() {
  console.log('Initializing PGlite (WASM Postgres)...');

  await db.exec(`
    CREATE TABLE IF NOT EXISTS releases (
      id TEXT PRIMARY KEY,
      brand TEXT NOT NULL,
      category TEXT NOT NULL,
      year TEXT NOT NULL,
      quarter TEXT NOT NULL,
      date_order INT NOT NULL,
      date_str TEXT NOT NULL,
      headline TEXT NOT NULL,
      subheadline TEXT,
      body_text TEXT,
      quote TEXT,
      quote_author TEXT,
      source_url TEXT,
      source_title TEXT,
      specs JSONB,
      highlights JSONB
    );

    CREATE TABLE IF NOT EXISTS cpu_models (
      id SERIAL PRIMARY KEY,
      cpu TEXT NOT NULL,
      url TEXT,
      family TEXT NOT NULL,
      brand TEXT NOT NULL,
      date TEXT NOT NULL,
      platform TEXT NOT NULL,
      cores_threads TEXT NOT NULL,
      cores INT,
      threads INT,
      igpu TEXT NOT NULL,
      arch TEXT NOT NULL,
      compute_cores INT,
      clock NUMERIC
    );

    CREATE TABLE IF NOT EXISTS amd_cpu_specs (
      id SERIAL PRIMARY KEY,
      name TEXT,
      family TEXT,
      series TEXT,
      launch_date TEXT,
      form_factor TEXT,
      of_cpu_cores INT,
      of_threads INT,
      max_boost_clock TEXT,
      base_clock TEXT,
      l1_cache TEXT,
      l2_cache TEXT,
      l3_cache TEXT,
      default_tdp TEXT,
      amd_configurable_tdp_ctdp TEXT,
      processor_technology_for_cpu_cores TEXT,
      cpu_socket TEXT,
      max_operating_temperature_tjmax TEXT,
      pci_express_version TEXT,
      system_memory_type TEXT,
      memory_channels NUMERIC,
      graphics_model TEXT,
      graphics_core_count INT,
      graphics_frequency TEXT,
      product_id_boxed TEXT,
      product_id_tray TEXT,
      product_id_mpk TEXT,
      supported_technologies TEXT
    );

    CREATE TABLE IF NOT EXISTS amd_igpu_specs (
      id SERIAL PRIMARY KEY,
      name TEXT,
      family TEXT,
      series TEXT,
      launch_date TEXT,
      processor_technology_for_cpu_cores TEXT,
      cpu_socket TEXT,
      pci_express_version TEXT,
      system_memory_type TEXT,
      graphics_model TEXT,
      graphics_core_count INT,
      graphics_frequency TEXT,
      supported_technologies TEXT
    );

    CREATE TABLE IF NOT EXISTS amd_cpu_series (
      id SERIAL PRIMARY KEY,
      series TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS amd_igpu_series (
      id SERIAL PRIMARY KEY,
      graphics_model TEXT NOT NULL
    );

    -- Intel Tables
    CREATE TABLE IF NOT EXISTS intel_cpu_specs (
      id SERIAL PRIMARY KEY,
      name TEXT NOT NULL,
      family TEXT NOT NULL,
      series TEXT NOT NULL,
      launch_date TEXT NOT NULL,
      socket TEXT NOT NULL,
      process_node TEXT,
      cores INT,
      threads INT,
      p_cores TEXT,
      e_cores TEXT,
      l3_cache TEXT,
      base_clock TEXT,
      boost_clock TEXT,
      tdp TEXT,
      memory_support TEXT,
      graphics_model TEXT,
      npu_tops TEXT,
      has_igpu BOOLEAN NOT NULL,
      igpu_suffix_rule TEXT
    );

    CREATE TABLE IF NOT EXISTS intel_igpu_specs (
      id SERIAL PRIMARY KEY,
      graphics_model TEXT NOT NULL,
      architecture TEXT NOT NULL,
      execution_units INT,
      xe_cores INT,
      launch_date TEXT NOT NULL,
      supported_sockets TEXT NOT NULL,
      performance_tier TEXT,
      memory_support TEXT,
      notes TEXT
    );

    CREATE TABLE IF NOT EXISTS intel_cpu_series (
      id SERIAL PRIMARY KEY,
      series TEXT NOT NULL,
      launch_date TEXT NOT NULL,
      socket TEXT NOT NULL,
      memory_support TEXT NOT NULL,
      chipsets TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS intel_igpu_series (
      id SERIAL PRIMARY KEY,
      graphics_model TEXT NOT NULL,
      era TEXT NOT NULL,
      architecture TEXT NOT NULL
    );

    -- Backward Compatibility Views
    DROP VIEW IF EXISTS cpu_specs CASCADE;
    DROP TABLE IF EXISTS cpu_specs CASCADE;
    DROP VIEW IF EXISTS igpu_specs CASCADE;
    DROP TABLE IF EXISTS igpu_specs CASCADE;
    DROP VIEW IF EXISTS cpu_series CASCADE;
    DROP TABLE IF EXISTS cpu_series CASCADE;
    DROP VIEW IF EXISTS igpu_series CASCADE;
    DROP TABLE IF EXISTS igpu_series CASCADE;

    CREATE OR REPLACE VIEW cpu_specs AS SELECT * FROM amd_cpu_specs;
    CREATE OR REPLACE VIEW igpu_specs AS SELECT * FROM amd_igpu_specs;
    CREATE OR REPLACE VIEW cpu_series AS SELECT * FROM amd_cpu_series;
    CREATE OR REPLACE VIEW igpu_series AS SELECT * FROM amd_igpu_series;
  `);

  // Check if cpu_models table is populated
  const cpuCountRes = await db.query('SELECT COUNT(*) as count FROM cpu_models');
  if (parseInt(cpuCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 40 AMD iGPU CPU models...');
    await seedCpuModels();
  }

  // Check if amd_cpu_specs table is populated
  const specsCountRes = await db.query('SELECT COUNT(*) as count FROM amd_cpu_specs');
  if (parseInt(specsCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 1-to-1 AMD CPU Specs (27 columns)...');
    await seedCpuSpecs();
  }

  // Check if amd_igpu_specs table is populated
  const igpuCountRes = await db.query('SELECT COUNT(*) as count FROM amd_igpu_specs');
  if (parseInt(igpuCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 1-to-1 AMD iGPU Specs (12 columns)...');
    await seedIgpuSpecs();
  }

  // Check if amd_cpu_series table is populated
  const cpuSeriesRes = await db.query('SELECT COUNT(*) as count FROM amd_cpu_series');
  if (parseInt(cpuSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with AMD CPU Series...');
    await db.query(`
      INSERT INTO amd_cpu_series (series) VALUES
      ('Ryzen AI PRO 400 Series'),
      ('Ryzen AI 400 Series'),
      ('Ryzen PRO 8000 Series'),
      ('Ryzen 8000 Series');
    `);
  }

  // Check if amd_igpu_series table is populated
  const igpuSeriesRes = await db.query('SELECT COUNT(*) as count FROM amd_igpu_series');
  if (parseInt(igpuSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with AMD iGPU Series...');
    await db.query(`
      INSERT INTO amd_igpu_series (graphics_model) VALUES
      ('AMD Radeon 860M'),
      ('AMD Radeon 840M'),
      ('AMD Radeon 780M'),
      ('AMD Radeon 760M'),
      ('AMD Radeon 740M');
    `);
  }

  // Check if intel_cpu_specs table is populated
  const intelCpuRes = await db.query('SELECT COUNT(*) as count FROM intel_cpu_specs');
  if (parseInt(intelCpuRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with Intel CPU Specs...');
    await seedIntelCpuSpecs();
  }

  // Check if intel_igpu_specs table is populated
  const intelIgpuRes = await db.query('SELECT COUNT(*) as count FROM intel_igpu_specs');
  if (parseInt(intelIgpuRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with Intel iGPU Specs...');
    await seedIntelIgpuSpecs();
  }

  // Check if intel_cpu_series table is populated
  const intelSeriesRes = await db.query('SELECT COUNT(*) as count FROM intel_cpu_series');
  if (parseInt(intelSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with Intel CPU Series & Sockets...');
    await seedIntelCpuSeries();
  }

  // Check if intel_igpu_series table is populated
  const intelIgpuSeriesRes = await db.query('SELECT COUNT(*) as count FROM intel_igpu_series');
  if (parseInt(intelIgpuSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with Intel iGPU Series...');
    await seedIntelIgpuSeries();
  }

  // Apply permanent column drop schema alterations saved in browser localStorage
  await applyDroppedColumnsFromStorage();
}

export async function applyDroppedColumnsFromStorage() {
  if (typeof localStorage === 'undefined') return;
  const tables = ['intel_cpu_specs', 'intel_igpu_specs', 'intel_cpu_series', 'intel_igpu_series', 'amd_cpu_specs', 'amd_igpu_specs', 'amd_cpu_series', 'amd_igpu_series', 'cpu_models'];
  for (const table of tables) {
    try {
      const saved = localStorage.getItem(`pglite_explorer_dropped_cols_${table}`);
      if (saved) {
        const dropped = JSON.parse(saved);
        for (const col of dropped) {
          await db.query(`ALTER TABLE ${table} DROP COLUMN IF EXISTS "${col}"`);
        }
      }
    } catch(e) {}
  }
}

