import { PGlite } from '@electric-sql/pglite';

export const db = new PGlite();

export async function initDatabase() {
  console.log('Initializing PGlite (WASM Postgres)...');

  await db.exec(`
    CREATE TABLE IF NOT EXISTS releases (
      id TEXT PRIMARY KEY,
      brand TEXT NOT NULL,
      category TEXT NOT NULL,
      year TEXT NOT NULL,
      quarter TEXT NOT NULL,
      date_order INT NOT NULL,
      date_str TEXT NOT NULL,
      headline TEXT NOT NULL,
      subheadline TEXT,
      body_text TEXT,
      quote TEXT,
      quote_author TEXT,
      source_url TEXT,
      source_title TEXT,
      specs JSONB,
      highlights JSONB
    );

    CREATE TABLE IF NOT EXISTS cpu_models (
      id SERIAL PRIMARY KEY,
      cpu TEXT NOT NULL,
      url TEXT,
      family TEXT NOT NULL,
      brand TEXT NOT NULL,
      date TEXT NOT NULL,
      platform TEXT NOT NULL,
      cores_threads TEXT NOT NULL,
      cores INT,
      threads INT,
      igpu TEXT NOT NULL,
      arch TEXT NOT NULL,
      compute_cores INT,
      clock NUMERIC
    );

    CREATE TABLE IF NOT EXISTS cpu_specs (
      id SERIAL PRIMARY KEY,
      name TEXT,
      family TEXT,
      series TEXT,
      launch_date TEXT,
      form_factor TEXT,
      of_cpu_cores INT,
      of_threads INT,
      max_boost_clock TEXT,
      base_clock TEXT,
      l1_cache TEXT,
      l2_cache TEXT,
      l3_cache TEXT,
      default_tdp TEXT,
      amd_configurable_tdp_ctdp TEXT,
      processor_technology_for_cpu_cores TEXT,
      cpu_socket TEXT,
      max_operating_temperature_tjmax TEXT,
      pci_express_version TEXT,
      system_memory_type TEXT,
      memory_channels NUMERIC,
      graphics_model TEXT,
      graphics_core_count INT,
      graphics_frequency TEXT,
      product_id_boxed TEXT,
      product_id_tray TEXT,
      product_id_mpk TEXT,
      supported_technologies TEXT
    );

    CREATE TABLE IF NOT EXISTS igpu_specs (
      id SERIAL PRIMARY KEY,
      name TEXT,
      family TEXT,
      series TEXT,
      launch_date TEXT,
      processor_technology_for_cpu_cores TEXT,
      cpu_socket TEXT,
      pci_express_version TEXT,
      system_memory_type TEXT,
      graphics_model TEXT,
      graphics_core_count INT,
      graphics_frequency TEXT,
      supported_technologies TEXT
    );

    CREATE TABLE IF NOT EXISTS cpu_series (
      id SERIAL PRIMARY KEY,
      series TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS igpu_series (
      id SERIAL PRIMARY KEY,
      graphics_model TEXT NOT NULL
    );
  `);

  // Check if cpu_models table is populated
  const cpuCountRes = await db.query('SELECT COUNT(*) as count FROM cpu_models');
  if (parseInt(cpuCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 40 AMD iGPU CPU models...');
    await seedCpuModels();
  }

  // Check if cpu_specs table is populated
  const specsCountRes = await db.query('SELECT COUNT(*) as count FROM cpu_specs');
  if (parseInt(specsCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 1-to-1 AMD CPU Specs (27 columns)...');
    await seedCpuSpecs();
  }

  // Check if igpu_specs table is populated
  const igpuCountRes = await db.query('SELECT COUNT(*) as count FROM igpu_specs');
  if (parseInt(igpuCountRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with 1-to-1 AMD iGPU Specs (12 columns)...');
    await seedIgpuSpecs();
  }

  // Check if cpu_series table is populated
  const cpuSeriesRes = await db.query('SELECT COUNT(*) as count FROM cpu_series');
  if (parseInt(cpuSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with CPU Series from Excel...');
    await db.query(`
      INSERT INTO cpu_series (series) VALUES
      ('Ryzen AI PRO 400 Series'),
      ('Ryzen AI 400 Series'),
      ('Ryzen PRO 8000 Series'),
      ('Ryzen 8000 Series');
    `);
  }

  // Check if igpu_series table is populated
  const igpuSeriesRes = await db.query('SELECT COUNT(*) as count FROM igpu_series');
  if (parseInt(igpuSeriesRes.rows[0].count, 10) === 0) {
    console.log('Seeding PGlite database with iGPU Series from Excel...');
    await db.query(`
      INSERT INTO igpu_series (graphics_model) VALUES
      ('AMD Radeon 860M'),
      ('AMD Radeon 840M'),
      ('AMD Radeon 780M'),
      ('AMD Radeon 760M'),
      ('AMD Radeon 740M');
    `);
  }
}

